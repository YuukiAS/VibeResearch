INSTRUMENTATION_WRAPPERS = [
    "environment_probe",
    "data_probe",
    "baseline_inventory",
    "evaluation_smoke",
    "metrics_export",
]
EXPERIMENT_WRAPPERS = ["baseline_compare", "train_smoke", "train_gate", "long_run_submit"]


def default_script_dir(paths: VibePaths) -> Path:
    return paths.vibe / "scripts"


def bootstrap_script_plan(paths: VibePaths, *, script_dir: str = ".vibe/scripts", generate: bool = True) -> Path:
    target_dir = paths.root / script_dir
    wrappers = INSTRUMENTATION_WRAPPERS + EXPERIMENT_WRAPPERS
    lines = [
        "# VibeResearch Script Bootstrap Plan",
        "",
        f"Generated at: `{utc_now()}`",
        f"Script directory: `{script_dir}`",
        "",
        "Generated wrappers are draft and untrusted until lint, contract-test, and adapter activation pass.",
        "",
        "## Recommended Wrappers",
        "",
    ]
    for name in wrappers:
        lines.extend(
            [
                f"### {name}",
                "",
                "- Purpose: provide a thin project-owned wrapper for this capability.",
                "- Existing entrypoint: unresolved by bootstrap discovery.",
                "- Required inputs: project-specific; answer adapter questions before activation.",
                "- Expected outputs: schema-valid metrics/artifacts declared in `.vibe/adapter.yaml`.",
                "- Contract test: dryrun must execute and expected metrics/artifacts must be produced or mocked.",
                "- Activation blockers: missing user answers, metrics schema, artifact rules, resource policy, or contract test.",
                "",
            ]
        )
    write_text(paths.vibe / "script_bootstrap_plan.md", "\n".join(lines))
    if generate:
        ensure_dir(target_dir)
        for name in wrappers:
            write_wrapper(target_dir / f"{name}.py", name)
    script_readiness_matrix(paths, script_dir=script_dir, write=True)
    return paths.vibe / "script_bootstrap_plan.md"


