def wrapper_inventory(paths: VibePaths, *, script_dir: str = ".vibe/scripts") -> list[dict[str, Any]]:
    root = paths.root / script_dir
    rows: list[dict[str, Any]] = []
    for name in INSTRUMENTATION_WRAPPERS + EXPERIMENT_WRAPPERS:
        path = root / f"{name}.py"
        rows.append({"id": name, "path": str(path), "exists": path.exists(), "status": "draft_untrusted" if path.exists() else "missing"})
    return rows


def script_readiness_matrix(paths: VibePaths, *, script_dir: str = ".vibe/scripts", write: bool = False) -> list[dict[str, Any]]:
    """Return script readiness with contract-oriented status fields."""

    root = paths.root / script_dir
    rows: list[dict[str, Any]] = []
    contract_dir = paths.vibe / "contract_tests"
    for name in INSTRUMENTATION_WRAPPERS + EXPERIMENT_WRAPPERS:
        path = root / f"{name}.py"
        contract = read_json(contract_dir / f"{name}.json", {}) if contract_dir.exists() else {}
        text = path.read_text(errors="ignore") if path.exists() else ""
        generated = "Generated by VibeResearch adapter bootstrap" in text
        placeholder = (not path.exists()) or is_placeholder_command(text[:300]) or "Draft wrapper is not active" in text
        status = "missing"
        if path.exists():
            status = "generated_draft" if generated else "existing"
            if placeholder:
                status = "needs_user_review"
            if name in {"evaluation_smoke", "baseline_compare"} and not project_eval_candidates(paths):
                status = "blocked_missing_project_eval"
            if contract.get("status") == "failed":
                status = "contract_failed"
            if contract.get("status") == "passed":
                status = "contract_passed" if generated else "active_reference"
        rows.append(
            {
                "id": name,
                "path": str(path.relative_to(paths.root)) if path.exists() else str(path),
                "exists": path.exists(),
                "status": status,
                "provenance": {"generated_by": "vibe script bootstrap" if generated else "project", "checked_at": utc_now()},
                "referenced_project_script": project_eval_candidates(paths)[:5],
                "input_contract": "project-specific; must be declared by adapter capability",
                "output_contract": f".vibe/bootstrap_metrics/{name}.json",
                "metrics_export_contract": "schema-valid JSON metrics required before trust",
                "dryrun_mode": "--dryrun",
                "smoke_mode": "--smoke",
                "failure_behavior": "non-zero exit or missing expected output blocks activation",
            }
        )
    if write:
        write_json(paths.vibe / "script_readiness.json", rows)
    return rows


def project_eval_candidates(paths: VibePaths) -> list[str]:
    candidates = []
    for pattern in ["*eval*.py", "*evaluate*.py", "*metric*.py", "*benchmark*.py"]:
        for path in sorted(paths.root.rglob(pattern)):
            if ".git" in path.parts or ".vibe" in path.parts or ".vibe_dogfood" in path.parts:
                continue
            if path.is_file():
                candidates.append(str(path.relative_to(paths.root)))
            if len(candidates) >= 20:
                return candidates
    return candidates
